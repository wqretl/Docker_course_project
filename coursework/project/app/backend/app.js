// =============================================================================
// Импорт зависимостей
// =============================================================================

// Express — минималистичный веб-фреймворк для Node.js.
// Предоставляет удобные методы для определения маршрутов (routes) HTTP-запросов,
// обработки параметров, заголовков и тел запросов/ответов.
const express = require("express");

// CORS (Cross-Origin Resource Sharing) — механизм, позволяющий браузеру
// выполнять запросы к серверу, расположенному на другом домене (или порту).
// В контейнерной среде frontend и backend могут быть доступны по разным адресам
// на этапе разработки, поэтому middleware cors() добавляет в ответы сервера
// заголовки, разрешающие кросс-доменные запросы.
const cors = require("cors");

// pg — клиентская библиотека для взаимодействия с СУБД PostgreSQL из Node.js.
// Pool — пул соединений: вместо того чтобы открывать и закрывать соединение
// с базой данных при каждом запросе, пул поддерживает набор открытых соединений
// и переиспользует их. Это снижает накладные расходы на установку TCP-соединения
// и аутентификацию при каждом обращении к базе.
const { Pool } = require("pg");

// =============================================================================
// Инициализация Express-приложения
// =============================================================================

// Создание экземпляра Express-приложения.
// Переменная app — центральный объект, к которому привязываются middleware
// (промежуточные обработчики) и маршруты (routes).
const app = express();

// Подключение middleware cors() — с этого момента ко всем ответам сервера
// будут добавляться заголовки Access-Control-Allow-Origin и другие,
// необходимые для корректной работы кросс-доменных запросов из браузера.
app.use(cors());

// Подключение встроенного middleware express.json() — он автоматически
// разбирает тело входящего HTTP-запроса, если оно имеет тип application/json,
// и помещает результат в свойство req.body. Без этого middleware обработчики
// маршрутов не смогут читать JSON-данные, отправленные клиентом.
app.use(express.json());

// =============================================================================
// Настройка подключения к базе данных
// =============================================================================

// Создание пула соединений с PostgreSQL. Параметры подключения читаются
// из переменных окружения (process.env), а если переменная не задана —
// используется значение по умолчанию после оператора ||.
//
// Такой подход позволяет не менять код приложения при развертывании
// в разных средах: параметры передаются через переменные окружения,
// которые задаются в docker-compose.yml, Kubernetes ConfigMap/Secret
// или при ручном запуске контейнера (флаг -e / --env).
const pool = new Pool({
  host: process.env.DB_HOST || "localhost",       // адрес сервера БД
  port: process.env.DB_PORT || 5432,              // порт PostgreSQL
  database: process.env.DB_NAME || "notes",       // имя базы данных
  user: process.env.DB_USER || "notes",           // имя пользователя БД
  password: process.env.DB_PASSWORD || "notes",   // пароль пользователя БД
});

// =============================================================================
// Инициализация базы данных
// =============================================================================

// Функция initDb() создает таблицу notes, если она еще не существует.
// В контейнерной среде backend и database запускаются одновременно,
// при этом база данных может быть еще не готова принимать соединения
// на момент старта backend. Поэтому функция выполняет до 30 попыток
// подключения с паузой в 1 секунду между ними. Такой механизм повторных
// попыток (retry loop) — типовой прием при работе с зависимыми сервисами
// в контейнерной среде.
async function initDb() {
  for (let attempt = 0; attempt < 30; attempt++) {
    try {
      // SQL-запрос CREATE TABLE IF NOT EXISTS создает таблицу только при
      // ее отсутствии. Это делает повторный запуск безопасным: если таблица
      // уже существует (например, данные сохранились в томе после перезапуска),
      // запрос не вызовет ошибку и не затронет существующие данные.
      //
      // Структура таблицы notes:
      //   id         — уникальный идентификатор, автоинкрементируемый (SERIAL)
      //   title      — заголовок заметки, обязательное поле (NOT NULL)
      //   content    — текст заметки, по умолчанию пустая строка
      //   created_at — время создания, автоматически заполняется текущим временем
      await pool.query(`
        CREATE TABLE IF NOT EXISTS notes (
          id SERIAL PRIMARY KEY,
          title TEXT NOT NULL,
          content TEXT NOT NULL DEFAULT '',
          created_at TIMESTAMP DEFAULT NOW()
        )
      `);
      // Если запрос выполнен успешно — таблица существует, выходим из функции.
      return;
    } catch {
      // Если подключение не удалось (PostgreSQL еще не запустился),
      // ожидаем 1 секунду перед следующей попыткой.
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
  // Если за 30 попыток (30 секунд) подключиться не удалось,
  // выбрасываем ошибку — приложение не сможет работать без базы данных.
  throw new Error("Could not connect to database");
}

// =============================================================================
// Маршруты (routes) API
// =============================================================================

// -----------------------------------------------------------------------------
// GET /api/health — проверка работоспособности (health check)
// -----------------------------------------------------------------------------
// Этот эндпоинт предназначен не для пользователя, а для инфраструктуры.
// Docker (инструкция HEALTHCHECK в Dockerfile) и Kubernetes (liveness/readiness
// probes) периодически обращаются к этому адресу, чтобы определить,
// работоспособен ли контейнер. Если эндпоинт возвращает HTTP 200 и
// {"status": "ok"} — приложение считается здоровым. Если база данных
// недоступна, возвращается HTTP 503 (Service Unavailable) с описанием ошибки,
// и оркестратор может перезапустить контейнер или исключить его из балансировки.
app.get("/api/health", async (_req, res) => {
  try {
    // Выполняем простейший SQL-запрос для проверки доступности БД.
    // Если соединение с PostgreSQL работает, запрос вернет результат мгновенно.
    await pool.query("SELECT 1");
    res.json({ status: "ok", version: "2.0" });
  } catch (e) {
    // Если запрос к БД завершился ошибкой (например, база недоступна),
    // возвращаем HTTP 503 с описанием проблемы.
    res.status(503).json({ status: "error", detail: e.message });
  }
});

// -----------------------------------------------------------------------------
// GET /api/notes — получение списка всех заметок
// -----------------------------------------------------------------------------
// Возвращает массив JSON-объектов, отсортированных по дате создания
// в обратном порядке (новые заметки — первыми). Клиент (frontend)
// вызывает этот эндпоинт при загрузке страницы и после каждого изменения.
app.get("/api/notes", async (_req, res) => {
  // pool.query() возвращает объект с несколькими свойствами;
  // деструктуризация { rows } извлекает массив строк-результатов запроса.
  const { rows } = await pool.query(
    "SELECT id, title, content, created_at FROM notes ORDER BY created_at DESC"
  );
  // Отправляем массив заметок в формате JSON. Express автоматически
  // устанавливает заголовок Content-Type: application/json.
  res.json(rows);
});

// -----------------------------------------------------------------------------
// POST /api/notes — создание новой заметки
// -----------------------------------------------------------------------------
// Ожидает JSON-тело запроса вида: { "title": "...", "content": "..." }.
// Поле title обязательно, content — необязательно (по умолчанию пустая строка).
// Возвращает созданную заметку с присвоенным id и временем создания.
app.post("/api/notes", async (req, res) => {
  // Деструктуризация тела запроса. Если тело отсутствует (req.body === null
  // или undefined), используем пустой объект {}, чтобы избежать ошибки.
  const { title, content } = req.body || {};

  // Валидация: заголовок обязателен. Если не передан — возвращаем HTTP 400
  // (Bad Request) с описанием ошибки. Это единственная точка валидации
  // в приложении, поскольку приложение учебное и входные данные минимальны.
  if (!title) {
    return res.status(400).json({ error: "title is required" });
  }

  // Параметризованный SQL-запрос: значения подставляются через плейсхолдеры
  // $1, $2, а сами значения передаются отдельным массивом. Это защищает
  // от SQL-инъекций — библиотека pg корректно экранирует все подставляемые
  // значения, поэтому пользовательский ввод не может изменить структуру запроса.
  //
  // Конструкция RETURNING возвращает вставленную строку целиком, включая
  // автоматически сгенерированные поля (id, created_at), — это избавляет
  // от необходимости выполнять отдельный SELECT после вставки.
  const { rows } = await pool.query(
    "INSERT INTO notes (title, content) VALUES ($1, $2) RETURNING id, title, content, created_at",
    [title, content || ""]
  );

  // Возвращаем созданную заметку с HTTP-статусом 201 (Created),
  // который по соглашениям REST указывает на успешное создание ресурса.
  res.status(201).json(rows[0]);
});

// -----------------------------------------------------------------------------
// DELETE /api/notes/:id — удаление заметки по идентификатору
// -----------------------------------------------------------------------------
// Параметр :id извлекается из URL (например, DELETE /api/notes/5).
// Если заметка с указанным id не найдена — возвращается HTTP 404.
app.delete("/api/notes/:id", async (req, res) => {
  // rowCount содержит количество строк, затронутых SQL-операцией.
  // Для DELETE это количество удаленных строк: 1 — если заметка найдена
  // и удалена, 0 — если заметки с таким id не существует.
  const { rowCount } = await pool.query(
    "DELETE FROM notes WHERE id = $1",
    [req.params.id]
  );

  // Если ни одна строка не была удалена — заметка не найдена.
  if (rowCount === 0) {
    return res.status(404).json({ error: "not found" });
  }

  // Подтверждаем удаление, возвращая идентификатор удаленной заметки.
  res.json({ deleted: Number(req.params.id) });
});

// =============================================================================
// Запуск сервера
// =============================================================================

// Порт, на котором сервер будет принимать HTTP-запросы.
// По умолчанию — 8000, но может быть переопределен через переменную окружения.
const PORT = process.env.PORT || 8000;

// Сначала инициализируем базу данных (дожидаемся создания таблицы),
// затем запускаем HTTP-сервер. Метод app.listen() начинает прослушивание
// входящих соединений на указанном порту. Адрес "0.0.0.0" означает,
// что сервер принимает соединения на всех сетевых интерфейсах контейнера —
// это необходимо для того, чтобы запросы из контейнерной сети (от nginx
// или от других подов в кластере Kubernetes) могли достичь сервера.
// Если указать "127.0.0.1" (localhost), сервер будет доступен только
// изнутри самого контейнера и не сможет обслуживать внешние запросы.
initDb().then(() => {
  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Backend listening on port ${PORT}`);
  });
});
